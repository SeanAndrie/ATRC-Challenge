from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import numpy as np

# Run standalone (`.venv/bin/python pipeline/tests/test_p2p_vs_pax.py`): the repo
# root has to be importable for `pipeline.*`, which is a namespace package here.
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from pipeline.competition import load as cl  # noqa: E402
from pipeline import paths                   # noqa: E402


def norm(s):
    return s.str.upper().str.strip()


def main():
    intl = cl.read_international_train()
    fa = cl.flights_monthly_agg()

    intl_m = intl.groupby(["ym", "Nationality"], dropna=False).agg(
        Guests=("Guests_n", "sum"),
        NewArr=("New Arrivals_n", "sum"),
        SameDay=("Same-Day Guests_n", "sum"),
        dates=("dt", "nunique"),
    ).reset_index()

    intl_m["Nationality_n"] = norm(intl_m["Nationality"])
    intl_m["ym_str"] = intl_m["ym"].astype(str)
    fa["Nationality_n"] = norm(fa["Departure Country Name"])
    fa["ym_str"] = fa["ym"].astype(str)
    m = intl_m.merge(
        fa[["ym_str", "Nationality_n", "Total_PAX", "Total_P2P", "Total_Seats", "Total_Transfer", "Total_Transit"]],
        on=["ym_str", "Nationality_n"],
        how="inner",
    )
    m = m.dropna(subset=["Total_PAX", "Total_P2P", "Guests"], how="any")
    if m.empty:
        raise SystemExit("No matched rows")

    m["PAX"] = m["Total_PAX"]
    m["P2P"] = m["Total_P2P"]
    m = m[(m["PAX"] > 0) & (m["P2P"] > 0) & (m["Guests"] > 0)]

    m["lGuests"] = np.log(m["Guests"])
    m["lPAX"] = np.log(m["PAX"])
    m["lP2P"] = np.log(m["P2P"])

    import statsmodels.formula.api as smf

    res_pax = smf.ols("lGuests ~ lPAX + C(ym_str) + C(Nationality_n)", data=m).fit()
    res_p2p = smf.ols("lGuests ~ lP2P + C(ym_str) + C(Nationality_n)", data=m).fit()

    out = paths.REPORT_P2P_VS_PAX
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w") as f:
        f.write("# PAX vs P2P — Gate Experiment\n\n")
        f.write(f"Matched rows: {len(m):,} (nationality × month)\n")
        f.write(f"Nationalities: {m['Nationality_n'].nunique()}, Months: {m['ym_str'].nunique()}\n\n")
        # coefficients
        f.write("## Coefficients (elasticity)\n")
        f.write("| model | variable | coef | std err | t | P>|t| | 95% CI\n")
        f.write("|---|---|---:|---:|---:|---:|---\n")
        for var in ["lPAX", "lP2P"]:
            r = res_pax if var=="lPAX" else res_p2p
            c = r.params.get(var)
            se = r.bse.get(var)
            if c is not None and se is not None:
                t = c/se
                p = r.pvalues.get(var, float("nan"))
                ci = r.conf_int().loc[var].to_list()
                f.write(f"| {'PAX' if var=='lPAX' else 'P2P'} | {var} | {c:.4f} | {se:.4f} | {t:.3f} | {p:.3f} | [{ci[0]:.4f}, {ci[1]:.4f}]\n")
        f.write("\n## R-squared\n")
        f.write(f"PAX R²={res_pax.rsquared:.4f}, adj={res_pax.rsquared_adj:.4f}\n")
        f.write(f"P2P R²={res_p2p.rsquared:.4f}, adj={res_p2p.rsquared_adj:.4f}\n\n")
        f.write(f"Generated by: pipeline/tests/test_p2p_vs_pax.py\n")


if __name__ == "__main__":
    main()
